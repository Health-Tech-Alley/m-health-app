const TRANSLATIONS: Record<AppLanguage, Partial<Record<TranslationKey, string>>> = {
  en: ENGLISH_TRANSLATIONS,
  es: SPANISH_TRANSLATIONS,
};

export function languageFromPreference(preference: string | null | undefined): AppLanguage {
  return preference === "Español" ? "es" : "en";
}

export function languagePreferenceFromLanguage(
  language: AppLanguage,
): SupportedAppLanguagePreference {
  return language === "es" ? "Español" : "English";
}

export function normalizeSupportedLanguagePreference(
  preference: string | null | undefined,
): SupportedAppLanguagePreference {
  return languagePreferenceFromLanguage(languageFromPreference(preference));
}

export function resolveActiveLanguagePreference({
  temporaryPreference,
  localPreference,
}: {
  temporaryPreference?: string | null;
  localPreference?: string | null;
}): string | null {
  return temporaryPreference ?? localPreference ?? null;
}

export function localeFromLanguage(language: AppLanguage): AppLocale {
  return language === "es" ? "es-US" : "en-US";
}

export function translate(
  key: TranslationKey,
  language: AppLanguage = "en",
  params?: TranslationParams,
): string {
  const template = TRANSLATIONS[language][key] ?? ENGLISH_TRANSLATIONS[key] ?? key;
  return interpolate(template, params);
}

export function languagePreferenceLabel(
  preference: string | null | undefined,
  t: TranslateFn,
): string {
  if (preference === "English") return t("common.language.english");
  if (preference === "Español") return t("common.language.spanish");
  if (preference === "English + Español") return t("common.language.englishSpanish");
  if (preference === "Other") return t("common.language.other");
  return preference?.trim() ?? "";
}

function interpolate(template: string, params?: TranslationParams): string {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (_match, name: string) => {
    const value = params[name];
    return value === undefined ? "" : String(value);
  });
}
